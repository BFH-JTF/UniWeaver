import { describe, expect, it } from 'vitest'
import { isRestrictableTable, priorityLabel, validateRestrictionParams } from './restrictions'

describe('isRestrictableTable', () => {
  it('accepts the known curriculum tables', () => {
    expect(isRestrictableTable('modules')).toBe(true)
    expect(isRestrictableTable('classes')).toBe(true)
    expect(isRestrictableTable('degrees')).toBe(true)
  })

  it('rejects unknown tables and empty strings', () => {
    expect(isRestrictableTable('users')).toBe(false)
    expect(isRestrictableTable('')).toBe(false)
    expect(isRestrictableTable('MODULES')).toBe(false)
  })
})

describe('priorityLabel', () => {
  it('maps the five documented weights to stable labels', () => {
    expect(priorityLabel(1)).toBe('Nice-to-have')
    expect(priorityLabel(3)).toBe('Standard importance')
    expect(priorityLabel(5)).toBe('Mandatory condition')
  })

  it('returns "" for weights outside 1..5 (incl. 0 and negatives)', () => {
    expect(priorityLabel(0)).toBe('')
    expect(priorityLabel(-1)).toBe('')
    expect(priorityLabel(9)).toBe('')
  })
})

describe('validateRestrictionParams', () => {
  it('returns an error string for unknown rule types', () => {
    expect(validateRestrictionParams('completely_unknown_rule', {})).toMatch(/Unknown restriction type/)
  })

  it('rejects non-object params with a clear message', () => {
    expect(validateRestrictionParams('module_no_overlap', 'not-an-object')).toMatch(/params must be an object/)
    expect(validateRestrictionParams('module_no_overlap', null)).toMatch(/params must be an object/)
    expect(validateRestrictionParams('module_no_overlap', [1, 2])).toMatch(/params must be an object/)
  })

  it('does not throw on odd inputs', () => {
    expect(() => validateRestrictionParams('', { foo: 'bar' })).not.toThrow()
  })
})
import { RESTRICTION_TYPES } from './restrictions'

/** Valid fixture value for one param spec, generated by type + requiredness. */
function validParamValue(type: string, required: boolean): unknown {
  switch (type) {
    case 'weekdayArray': return ['friday']
    case 'buildingArray': return ['B1']
    case 'roomArray': return ['A 101']
    case 'moduleArray': return ['mod-a']
    case 'phaseArray': return ['morning', 'afternoon']
    case 'dateArray': return required ? ['2027-03-04'] : []
    case 'singleWeekday': return 'friday'
    case 'number': return 3
    case 'choice': return undefined // resolved from spec options below
    case 'timeslotArray': return ['08:00', '09:00']
    case 'stringArray': return ['A 101']
    case 'string': return 'Text'
    default: return undefined
  }
}

describe('RESTRICTION_TYPES catalog validation (all types', () => {
  for (const [ruleType, spec] of Object.entries(RESTRICTION_TYPES)) {
    it(`accepts valid params for ${ruleType} and rejects corrupted ones`, () => {
      const params: Record<string, unknown> = {}
      for (const param of spec.params) {
        const val = param.type === 'choice'
          ? param.options?.[0]?.value
          : validParamValue(param.type, !!param.required)
        if (param.required) {
          expect(val !== undefined && val !== '', `${ruleType}.${param.key} fixture`).toBe(true)
        }
        params[param.key] = val
      }
      expect(validateRestrictionParams(ruleType, params)).toBeNull()

      // corrupt: an array param with a bad value / required param missing
      const arrayType = spec.params.find(p => p.required && (p.type === 'weekdayArray' || p.type === 'phaseArray' || p.type === 'dateArray' || p.type === 'timeslotArray' || p.type === 'buildingArray' || p.type === 'roomArray' || p.type === 'moduleArray'))
      if (arrayType) {
        expect(validateRestrictionParams(ruleType, { ...params, [arrayType.key]: 'nonsense' })).not.toBeNull()
        expect(validateRestrictionParams(ruleType, { ...params, [arrayType.key]: [] })).not.toBeNull()
      } else {
        const requiredParam = spec.params.find(p => p.required)
        if (requiredParam) expect(validateRestrictionParams(ruleType, {})).not.toBeNull()
      }
    })
  }
})
